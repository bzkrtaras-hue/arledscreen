// Generates functions/api/_melis-kb.js from docs/melis-knowledge-base.md (verified knowledge base for Melis).
// Run: npm run melis:kb   Panel prices are NOT taken from here (they come from src/content/prices.ts via _melis-prices.js).
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../docs/melis-knowledge-base.md", import.meta.url), "utf8");
const cut = (from, to) => { const a = src.indexOf(from), b = src.indexOf(to, a + 1); if (a < 0 || b < 0) throw new Error("kb markers missing: " + from); return [a, b]; };
let [a, b] = cut("## 1. Kimlik ve iletişim", "### 4.1 Panel fiyatları");
let body = src.slice(a, b);
let [c, d] = cut("### 4.3 Fiyatı yayımlanmayanlar", "## DOĞRULANMADI");
body += "\n" + src.slice(c, d);
let [e, f] = cut("## DOĞRULANMADI", "## Kaynaklar arasındaki çelişkiler");
body += "\n" + src.slice(e, f);
body = body
  .replace(/\s*\[[^\]\n]*(?:ARAS|prices\.ts|faqs\.ts|sss\.json|llms|models\.ts|control\.ts|kurulum|kiralama|AGENTS|git:|türetildi|Bu uyarı)[^\]\n]*\]/g, "") // drop source tags
  .replace(/^\|[-| ]+\|$/gm, "")
  .replace(/\n{3,}/g, "\n\n")
  .trim();
writeFileSync(new URL("../functions/api/_melis-kb.js", import.meta.url), `// AUTO-GENERATED by scripts/gen-melis-kb.mjs from docs/melis-knowledge-base.md — do not edit.\nexport const KB = ${JSON.stringify(body)};\n`);
console.log("melis kb:", body.length, "chars");
