#!/usr/bin/env node
// GEO paket 3: writes src/content/guide-dates.ts from real git history.
//   datePublished = author date of the first commit that introduced the guide
//                   (pickaxe on its slug in the guide's content file, or file add for markdown).
//   i18nModified  = last commit touching src/content/seo-guides-i18n.ts (AR/RU copy source).
// Nothing is invented: if git has no answer for a slug the script fails.
// Run from the repo root on a full (non-shallow) clone:  node scripts/generate-guide-dates.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const git = (...a) => execFileSync("git", a, { encoding: "utf8" }).trim();
if (git("rev-parse", "--is-shallow-repository") !== "false") {
  console.error("generate-guide-dates: shallow clone — need full history");
  process.exit(1);
}
const day = (iso) => iso.slice(0, 10);
const firstPick = (file, needle) => {
  const out = git("log", "-S" + needle, "--format=%aI", "--reverse", "--", file).split("\n")[0];
  if (!out) throw new Error(`no git history for ${needle} in ${file}`);
  return day(out);
};
const firstAdd = (file) => {
  const out = git("log", "--diff-filter=A", "--format=%aI", "--reverse", "--", file).split("\n")[0];
  if (!out) throw new Error(`no add commit for ${file}`);
  return day(out);
};
const slugs = (file, re) => [...fs.readFileSync(file, "utf8").match(re)[0].matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]);

const seo = slugs("src/content/seo-guides.ts", /SEO_GUIDE_SLUGS = \[[\s\S]*?\] as const/);
const inst = slugs("src/content/install-guides.ts", /INSTALL_GUIDE_SLUGS = \[[\s\S]*?\] as const/);
const md = fs.readdirSync("src/content/articles").filter((f) => f.endsWith(".md")).map((f) => f.replace(/\.md$/, ""));

const published = {};
for (const s of seo) published[s] = firstPick("src/content/seo-guides.ts", `slug: "${s}"`);
for (const s of inst) published[s] = firstPick("src/content/install-guides-tr.ts", `slug: "${s}"`);
for (const s of md) published[s] = firstAdd(`src/content/articles/${s}.md`);
const enCommercial = {};
for (const s of md) {
  try { enCommercial[s] = firstPick("src/content/commercial-guides-en.ts", `slug: "${s}"`); } catch { /* no EN landing */ }
}
const i18nModified = day(git("log", "-1", "--format=%aI", "--", "src/content/seo-guides-i18n.ts"));
const enModified = day(git("log", "-1", "--format=%aI", "--", "src/content/commercial-guides-en.ts"));

const body = `/**
 * GENERATED by scripts/generate-guide-dates.mjs from git history — do not edit by hand.
 * datePublished = first commit that introduced the guide (author date, YYYY-MM-DD).
 * Guides that already existed in the 4 Oct 2026 source import carry that import date.
 */
export const GUIDE_PUBLISHED: Record<string, string> = ${JSON.stringify(published, null, 2)};

/** EN commercial guide landing pages: first commit of their EN copy. */
export const GUIDE_EN_PUBLISHED: Record<string, string> = ${JSON.stringify(enCommercial, null, 2)};

/** Last commit touching the AR/RU guide copy (seo-guides-i18n.ts); used where no visible review date exists. */
export const GUIDE_I18N_MODIFIED = ${JSON.stringify(i18nModified)};

/** Last commit touching the EN commercial guide copy; used for guides without a visible review date. */
export const GUIDE_EN_MODIFIED = ${JSON.stringify(enModified)};
`;
fs.writeFileSync("src/content/guide-dates.ts", body);
console.log("generate-guide-dates: wrote", Object.keys(published).length, "guides");
