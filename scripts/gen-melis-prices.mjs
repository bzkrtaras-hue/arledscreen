// Generates functions/api/_melis-prices.js from src/content/prices.ts (single source of truth).
// Run: npm run melis:prices
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../src/content/prices.ts", import.meta.url), "utf8");
const block = src.slice(src.indexOf("export const PANEL_PRICES"));
const end = block.indexOf("];");
const rows = [];
for (const line of block.slice(0, end).split("\n")) {
  const id = line.match(/id: "([^"]+)"/); if (!id) continue;
  const g = (k) => (line.match(new RegExp(k + ': ("[^"]*"|[\\d.]+|true)')) || [])[1];
  rows.push({ id: id[1], pitch: JSON.parse(g("pitch")), use: JSON.parse(g("use")), gob: g("surface") === '"GOB"', front: g("frontService") === "true", usd: Number(g("usd")), moduleMm: g("moduleMm") ? JSON.parse(g("moduleMm")) : "320 × 160 mm", path: g("productPath") ? JSON.parse(g("productPath")) : null });
}
const ex = src.match(/laborPerM2: (\d+),\s*controlCard: (\d+),\s*driverSoftware: (\d+)/);
const valid = src.match(/PRICE_VALID_UNTIL = "([^"]+)"/)[1];
if (rows.length < 10 || !ex) throw new Error("price parse failed");
const out = `// AUTO-GENERATED by scripts/gen-melis-prices.mjs from src/content/prices.ts — do not edit.\nexport const PANELS = ${JSON.stringify(rows, null, 1)};\nexport const EXTRAS = { laborPerM2: ${ex[1]}, controlCard: ${ex[2]}, driverSoftware: ${ex[3]} };\nexport const PRICE_VALID_UNTIL = ${JSON.stringify(valid)};\n`;
writeFileSync(new URL("../functions/api/_melis-prices.js", import.meta.url), out);
console.log("melis prices:", rows.length, "panels");
